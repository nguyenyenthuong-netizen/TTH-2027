import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const base=dirname(fileURLToPath(import.meta.url));
const data=execFileSync('unzip',['-p',join(base,'website.zip'),'index.html'],{maxBuffer:64*1024*1024});
const digest=createHash('sha256').update(data).digest('hex');
if(data.length!==35958380||digest!=='5cdf1b5869cc65ad02019641d335a8d4c140f8c7735cfa7cffaef1631a94fc31')throw Error('Website release checksum mismatch');
const destination=process.argv[2]||join(base,'dist');
mkdirSync(destination,{recursive:true});writeFileSync(join(destination,'index.html'),data);
console.log(`Published ${data.length} bytes; sha256 ${digest}`);
