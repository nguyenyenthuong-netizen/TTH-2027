import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { createHash } from 'node:crypto';
const base=dirname(new URL(import.meta.url).pathname);
const manifest=JSON.parse(readFileSync(join(base,'manifest.json'),'utf8'));
const names=readdirSync(join(base,'parts')).filter(n=>n.startsWith('part-')).sort();
if(names.length!==manifest.parts)throw Error(`Expected ${manifest.parts} parts, got ${names.length}`);
const data=Buffer.concat(names.map(n=>readFileSync(join(base,'parts',n))));
const digest=createHash('sha256').update(data).digest('hex');
if(data.length!==manifest.size||digest!==manifest.sha256)throw Error('Website release checksum mismatch');
let html=data.toString('utf8');
const cssStart=html.indexOf('<style id="qc146-stable-package-cards">');
const cssEnd=html.indexOf('</style>',cssStart)+8;
if(cssStart<0||cssEnd<8)throw Error('Package card CSS missing');
let css=html.slice(cssStart,cssEnd).replaceAll('body.portal-site #app','body #app');
if(!css.includes('figure>img{width:100%!important;height:auto!important;aspect-ratio:4/3'))throw Error('Package picture CSS changed');
css=css.replace('figure>img{width:100%!important;height:auto!important;aspect-ratio:4/3','figure>img{width:100%!important;height:100%!important;aspect-ratio:4/3');
html=html.slice(0,cssStart)+css+html.slice(cssEnd);
const duplicate=', {"route": "#med-facility", "title": "Hồ sơ cơ sở"}';
if(html.split(duplicate).length!==6)throw Error('Facility menu count changed');
html=html.replaceAll(duplicate,'');
const oldTth='{"route": "#med-facility", "title": "Thông tin bệnh viện"}';
if(html.split(oldTth).length!==2)throw Error('TTH facility menu changed');
html=html.replace(oldTth,'{"route": "#facilities", "title": "Bệnh viện theo địa phương"}');
const final=Buffer.from(html,'utf8');
const finalDigest=createHash('sha256').update(final).digest('hex');
if(finalDigest!=='125d06a5cb7713fa673f291e9784e4330ad6708edca18941a49f622b24cd59a3')throw Error('Final QA checksum mismatch');
const destination=process.argv[2]||join(base,'dist');
mkdirSync(destination,{recursive:true});writeFileSync(join(destination,'index.html'),final);
console.log(`Published ${final.length} bytes; sha256 ${finalDigest}`);
